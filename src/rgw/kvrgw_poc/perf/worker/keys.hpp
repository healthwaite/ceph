// Key generation and shard math for the kvrgw perf worker (spec sections 5.2, 5.3).
#pragma once

#include <cstdint>
#include <optional>
#include <string>
#include <string_view>
#include <vector>

namespace perfw {

// Charset for random key prefixes (no '/').
inline constexpr std::string_view kCharset =
    "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ!-_.*'()";

constexpr uint64_t kSplitMixInc = 0x9e3779b97f4a7c15ULL;

// One SplitMix64 step on a state; advances the state.
uint64_t splitmix64_next(uint64_t &state);
// Stateless mix: splitmix64_next applied to a copy of x.
uint64_t splitmix64_mix(uint64_t x);

// padding bytes drawn from kCharset, generated by SplitMix64 from seed.
std::string rand_prefix(uint64_t seed, int padding_bytes);

// Load key: rand_prefix(i) + "%020d"(i)   (length padding + 20).
std::string load_key(uint64_t index, int padding_bytes);

// run-put-object key: rand_prefix(seed) + hex8(ts) + hex4(gtid) + "%020d"(counter)
// (length padding + 32).
uint64_t put_key_seed(uint64_t ts, uint64_t gtid, uint64_t counter);
std::string put_key(uint64_t ts, uint32_t gtid, uint64_t counter, int padding_bytes);
inline size_t put_key_len(int padding) { return static_cast<size_t>(padding) + 32; }
inline size_t load_key_len(int padding) { return static_cast<size_t>(padding) + 20; }

struct ParsedPutKey {
  uint64_t ts;
  uint32_t gtid;
  uint64_t counter;
};
// Parse the structured tail of a put key; nullopt if malformed.
std::optional<ParsedPutKey> parse_put_key(std::string_view key, int padding_bytes);

// Last 20 chars as a decimal id; nullopt if not exactly 20 digits.
std::optional<uint64_t> parse_key_id(std::string_view key);

std::string bucket_name(std::string_view prefix, uint64_t index);

// block_for_index: which of `parts` contiguous blocks (first n%parts get one extra)
// the index falls in. bucket_for_index is block_for_index over num_buckets.
uint64_t block_for_index(uint64_t i, uint64_t total, uint64_t parts);
inline uint64_t bucket_for_index(uint64_t i, uint64_t num_objects, uint64_t num_buckets) {
  return block_for_index(i, num_objects, num_buckets);
}

struct Range {
  uint64_t start = 0;
  uint64_t count = 0;
  uint64_t end() const { return start + count; }
};
// Contiguous block `part` of `parts` over [0,total).
Range block_range(uint64_t part, uint64_t parts, uint64_t total);
inline Range index_range(uint64_t gtid, uint64_t total_threads, uint64_t num_objects) {
  return block_range(gtid, total_threads, num_objects);
}
// Overwrite window of thread `gtid`: the first part of its own index range, sized so that the
// windows of all `total_threads` threads add up to `total_to_overwrite` (shared evenly, the
// remainder going to the first threads) and never exceed the thread's range. 0 means no limit:
// the whole range. With total_to_overwrite <= num_objects no thread is ever clamped.
inline Range overwrite_window(uint64_t gtid, uint64_t total_threads, uint64_t num_objects,
                              uint64_t total_to_overwrite) {
  Range r = index_range(gtid, total_threads, num_objects);
  if (total_to_overwrite != 0) {
    const uint64_t share = block_range(gtid, total_threads, total_to_overwrite).count;
    if (share < r.count) r.count = share;
  }
  return r;
}
inline Range bucket_range(uint64_t bucket, uint64_t num_buckets, uint64_t num_objects) {
  return block_range(bucket, num_buckets, num_objects);
}

// Worker owning bucket b.
inline int bucket_owner(uint64_t b, int worker_count) {
  return static_cast<int>(b % static_cast<uint64_t>(worker_count));
}
std::vector<uint64_t> owned_buckets(int worker_index, int worker_count, uint64_t num_buckets);

// Work items for prefix-partitioned scans: each charset char, or {""} if padding==0.
std::vector<std::string> prefix_items(int padding_bytes);

}  // namespace perfw
